// Helper to find curriculum item matching user query
export function findCurriculumMatch(query: string): CurriculumItem | null {
  const q = query.trim().toLowerCase();
  
  // Direct check for "البطل الخفي"
  if (q.includes('بطل') && (q.includes('خفي') || q.includes('الخفي') || q.includes('أمين') || q.includes('امين'))) {
    return CURRICULUM_DATABASE.find(item => item.id === 'lesson-al-batal-al-khafi') || null;
  }
  
  if (q.includes('خفي') || q.includes('الخفي')) {
    return CURRICULUM_DATABASE.find(item => item.id === 'lesson-al-batal-al-khafi') || null;
  }

  // Check keywords
  for (const item of CURRICULUM_DATABASE) {
    if (item.keywords.some(k => q.includes(k.toLowerCase()))) {
      return item;
    }
  }

  return null;
}
