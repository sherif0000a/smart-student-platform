// Arabic normalization helper
export function normText(txt: string): string {
  if (!txt) return '';
  return txt
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // strip tashkeel
    .replace(/[إأآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ئ/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/[؟?.,!:]/g, '')
    .trim();
}

